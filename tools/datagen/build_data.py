#!/usr/bin/env python3
"""Builds js/data.js from the raw dumps produced by dump.c / spnames.c.

Usage (from the repo root):
    python3 tools/datagen/build_data.py

Inputs (in tools/datagen/):
    gamedata.json  - output of the compiled dump.c (see tools/datagen/README.md)
    spnames.txt    - "<id> SPECIES_CONSTANT" lines, output of the compiled spnames.c
"""
import json
import os
import re
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))

raw = json.load(open(os.path.join(HERE, "gamedata.json"), encoding="utf-8"))

# ---------------------------------------------------------------------------
# Species constant names -> pretty form labels
# ---------------------------------------------------------------------------
const_by_id = {}
SKIP = re.compile(r"^SPECIES_(NONE|EGG|SHINY_TAG|.*_START|.*_END|.*_FIRST|.*_LAST|NUM_.*)$")
for line in open(os.path.join(HERE, "spnames.txt"), encoding="utf-8"):
    sid, name = line.split()
    sid = int(sid)
    if SKIP.match(name):
        continue
    const_by_id.setdefault(sid, []).append(name[len("SPECIES_"):])


def norm(s):
    s = unicodedata.normalize("NFKD", s)
    s = "".join(c for c in s if not unicodedata.combining(c))
    s = s.replace("♀", "F").replace("♂", "M")
    return re.sub(r"[^A-Z0-9]", "", s.upper())


def form_label(name, consts):
    base = norm(name)
    best = None
    for c in consts:
        toks = c.split("_")
        for k in range(1, len(toks) + 1):
            if "".join(toks[:k]) == base:
                suffix = toks[k:]
                if best is None or len(suffix) < len(best):
                    best = suffix
                break
    if best is None:
        return None
    if not best:
        return ""
    return " ".join(t.capitalize() for t in best)


species = []
for sid, s in enumerate(raw["species"]):
    name, hp, atk, df, spe, spa, spd, growth, gender, a0, a1, a2, t0, t1, dex = s
    label = name
    consts = const_by_id.get(sid, [])
    if name and consts:
        suffix = form_label(name, consts)
        if suffix:
            label = "%s (%s)" % (name, suffix)
        elif suffix is None:
            # In-game names are capped at 10 characters ("Flechinder"); use the constant instead
            label = consts[0].replace("_", " ").title()
    species.append([label, [hp, atk, df, spe, spa, spd], gender, [a0, a1, a2], [t0, t1], dex])

moves = [[m[0], m[1], m[2], m[3], m[4]] for m in raw["moves"]]
items = [[it[0] if it[2] else "", it[1] if it[2] else 0] for it in raw["items"]]

unlocks = json.load(open(os.path.join(HERE, "unlocks.json"), encoding="utf-8"))
for u in unlocks["hubUpgrades"]:
    if u:
        u[0] = re.sub(r"\s+", " ", u[0].replace("{PKMN}", " Pokémon ").replace("{POKEBLOCK}", "Pokéblock")).strip()

out = {
    "game": "Pokemon Emerald Rogue EX",
    "numSpecies": len(species),
    "species": species,
    "moves": moves,
    "abilities": raw["abilities"],
    "natures": raw["natures"],
    "items": items,
    "types": ["Normal", "Fighting", "Flying", "Poison", "Ground", "Rock", "Bug", "Ghost",
              "Steel", "???", "Fire", "Water", "Grass", "Electric", "Psychic", "Ice",
              "Dragon", "Dark", "Fairy", "Stellar"],
    "quests": unlocks["quests"],
    "hubAreas": unlocks["hubAreas"],
    "hubUpgrades": unlocks["hubUpgrades"],
    "flags": unlocks["flags"],
    "vars": unlocks["vars"],
    "pockets": ["None", "Items", "Held Items", "Medicine", "Stones", "Poké Balls",
                "TMs & HMs", "Berries", "Pokéblock", "Key Items"],
}

js = ("// Generated by tools/datagen/build_data.py from the Emerald Rogue EX source.\n"
      "// Do not edit by hand.\n"
      "(function (root) {\n  var DATA = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n"
      "  if (typeof module !== 'undefined' && module.exports) module.exports = DATA;\n"
      "  else root.ER_DATA = DATA;\n})(this);\n")
open(os.path.join(ROOT, "js", "data.js"), "w", encoding="utf-8").write(js)
print("species", len(species), "moves", len(moves), "items", len(items), "bytes", len(js))
